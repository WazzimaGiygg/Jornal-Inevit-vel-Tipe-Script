export function getLocalizedArticle(article: any, lang: LanguageCode): any {
  if (!article) return article;

  if (article.isMultiLanguage && article.translations && article.translations[lang]) {
    const tr = article.translations[lang];
    return {
      ...article,
      titulo: tr.titulo || article.titulo,
      resumo: tr.resumo || article.resumo,
      conteudo: tr.conteudo || article.conteudo,
      _currentLanguage: lang,
      _isFallback: false,
      _availableLanguages: article.languages || ['pt']
    };
  }

  // Fallback to Portuguese or original
  return {
    ...article,
    _currentLanguage: 'pt',
    _isFallback: lang !== 'pt',
    _availableLanguages: article.languages || ['pt']
  };
}
